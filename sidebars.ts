import type {SidebarsConfig} from '@docusaurus/plugin-content-docs';
import fs from 'node:fs';

// std.json, design.json and examples.json are written by scripts/sync.mjs.
function generated(name: string, fallback: unknown[]): any[] {
  try {
    return JSON.parse(fs.readFileSync(`generated/${name}.json`, 'utf8'));
  } catch {
    return fallback as any[];
  }
}

const sidebars: SidebarsConfig = {
  guide: [{type: 'autogenerated', dirName: 'guide'}],
  spec: [{type: 'autogenerated', dirName: 'spec'}],
  design: generated('design', []),
  std: generated('std', []),
  // The index page, then one page per example project (scripts/sync.mjs).
  examples: ['examples', ...generated('examples', [])],
  editors: [{type: 'autogenerated', dirName: 'editors'}],
  download: ['download'],
};

export default sidebars;
